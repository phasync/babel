<?php
// Regenerates tests/cases/r2_e2e_01.php, a phar whose stub maps itself. Usage: php -d phar.readonly=0 tests/e2e/make-phar-case.php
$tmp = sys_get_temp_dir() . '/r2_e2e_01-' . getmypid() . '.phar';
$p = new Phar($tmp);
$p->addFromString('x.php', "<?php echo 'inside the phar: ', basename(__FILE__), \"\\n\";\n");
$p->setStub("<?php\n// r2_e2e_01: a phar stub (generated by tests/e2e/make-phar-case.php). Translating it changes the bytes that\n// the phar signature covers, and Phar::mapPhar() reads the file that is executing: the cached copy.\nPhar::mapPhar('r2_e2e_01.phar');\ninclude 'phar://r2_e2e_01.phar/x.php';\necho \"done\\n\";\n__HALT_COMPILER();");
unset($p);
rename($tmp, __DIR__ . '/../cases/r2_e2e_01.php');
