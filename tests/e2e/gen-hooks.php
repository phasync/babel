<?php
// Generates tests/e2e/gen/hooks.php (pass-through replacements for internal functions) and
// tests/e2e/gen/map.php (the Babel function map). Usage: php tests/e2e/gen-hooks.php
//
// Every hook E2E\Hook\name has the internal function's signature: same parameter names (named
// arguments keep working), the same defaults (named-argument skipping fills the same values PHP
// would), by-reference parameters stay by reference, and the internal parameter types are declared
// with null added, so a caller's strict_types decides scalar coercion at the hook boundary as it
// would at the internal call, while null still reaches the internal function (which emits its own
// deprecation instead of the TypeError a userland non-nullable type would throw). Every parameter
// gets a default and the call is dispatched on func_num_args(), so an internal function never sees
// an argument the caller did not pass and argument-count errors come from the internal function.
//
// Not hooked (calling them one frame deeper changes their meaning):
//   str* (except stream_*) and array_*      - excluded by the task
//   compact, extract, get_defined_vars       - operate on the caller's variable scope
//   func_get_args, func_get_arg, func_num_args - the caller's arguments
//   debug_backtrace, debug_print_backtrace    - the caller's stack
//   get_called_class, get_class, get_parent_class (no-argument forms use the calling scope)
//   get_object_vars, get_class_vars, get_class_methods - visibility depends on the calling scope
//   constant, defined                         - self::/private class constants use the calling scope
//   is_callable and every function taking a callable (usort, preg_replace_callback(_array),
//     call_user_func*, forward_static_call*, set_error_handler, spl_autoload_register, ob_start,
//     register_shutdown_function, iterator_apply, ...) - 'self::m', [$this, 'privateMethod'] and
//     static:: callables are resolved in the calling frame's scope
//   trigger_error, user_error                 - exist to report the caller's file/line
//   assert                                    - compiled specially (zend.assertions, message text)
//   debug_zval_dump                           - prints refcounts, which the extra frame changes
//   exit, die, clone                          - keywords: cannot be declared, calls never reach the map
$exclude = array_flip([
    'compact', 'extract', 'get_defined_vars', 'func_get_args', 'func_get_arg', 'func_num_args',
    'debug_backtrace', 'debug_print_backtrace', 'get_called_class', 'get_class', 'get_parent_class',
    'get_object_vars', 'get_class_vars', 'get_class_methods', 'constant', 'defined', 'is_callable',
    'trigger_error', 'user_error', 'assert', 'debug_zval_dump', 'exit', 'die',
    'preg_replace_callback_array',
]);

function typeCode(?ReflectionType $t): string
{
    if ($t === null) {
        return '';
    }
    $one = static fn (ReflectionNamedType $n) => $n->isBuiltin() ? $n->getName() : '\\' . $n->getName();
    if ($t instanceof ReflectionNamedType) {
        if ($t->getName() === 'mixed' || $t->getName() === 'null') {
            return $t->getName() . ' ';
        }
        return '?' . $one($t) . ' ';
    }
    if ($t instanceof ReflectionUnionType) {
        $parts = [];
        foreach ($t->getTypes() as $p) {
            $parts[] = $p instanceof ReflectionNamedType ? $one($p) : '(' . implode('&', array_map($one, $p->getTypes())) . ')';
        }
        if (!$t->allowsNull()) {
            $parts[] = 'null';
        }
        return implode('|', $parts) . ' ';
    }
    return ''; // intersection types: leave untyped
}

$out = "<?php\n// GENERATED by tests/e2e/gen-hooks.php - do not edit.\nnamespace E2E { final class C { public static array \$n = []; } }\nnamespace E2E\\Hook {\n";
$map = [];
$skipped = [];
$noDefault = [];
foreach (get_defined_functions()['internal'] as $name) {
    if ((str_starts_with($name, 'str') && !str_starts_with($name, 'stream_')) || str_starts_with($name, 'array_') || isset($exclude[$name])) {
        $skipped[] = $name;
        continue;
    }
    if (token_get_all("<?php $name")[1][0] !== T_STRING) { // keywords: exit, die, clone (8.5) ...
        $skipped[] = $name;
        continue;
    }
    $rf = new ReflectionFunction($name);
    $params = $rf->getParameters();
    $callable = false;
    foreach ($params as $p) {
        $ts = (string) $p->getType();
        if (str_contains($ts, 'callable') || preg_match('/callback|handler/i', $p->getName())) {
            $callable = true;
        }
    }
    if ($callable) {
        $skipped[] = $name;
        continue;
    }
    $decl = [];
    $fixed = [];
    $variadic = null;
    $required = 0;
    foreach ($params as $p) {
        $v = '$' . $p->getName();
        if ($p->isVariadic()) {
            $decl[] = ($p->isPassedByReference() ? '' : typeCode($p->getType())) . ($p->isPassedByReference() ? '&' : '') . '...' . $v;
            $variadic = $v;
            continue;
        }
        if (!$p->isOptional()) {
            ++$required;
        }
        $def = 'null';
        if ($p->isOptional()) {
            if ($p->isDefaultValueAvailable()) {
                $dv = $p->getDefaultValue();
                if (is_object($dv) && !$dv instanceof UnitEnum) {
                    $noDefault[] = "$name(\${$p->getName()}) object default";
                } else {
                    $def = is_object($dv) ? '\\' . get_class($dv) . '::' . $dv->name : var_export($dv, true);
                    $def = str_replace("\n", ' ', $def);
                }
            } else {
                $noDefault[] = "$name(\${$p->getName()})";
            }
        }
        $decl[] = ($p->isPassedByReference() ? '&' : typeCode($p->getType())) . $v . ' = ' . $def;
        $fixed[] = $v;
    }
    $k = count($fixed);
    $body = "    \\E2E\\C::\$n['$name'] = (\\E2E\\C::\$n['$name'] ?? 0) + 1;\n    switch (\\func_num_args()) {\n";
    for ($i = 0; $i < $k; ++$i) {
        $body .= "        case $i: return \\$name(" . implode(', ', array_slice($fixed, 0, $i)) . ");\n";
    }
    if ($variadic !== null) {
        $body .= "        default: return \\$name(" . implode(', ', [...$fixed, '...' . $variadic]) . ");\n";
    } else {
        $body .= "        case $k: return \\$name(" . implode(', ', $fixed) . ");\n";
        $body .= "        default: return \\$name(...\\func_get_args());\n"; // too many: let the internal function complain
    }
    $body .= "    }\n";
    $out .= "function $name(" . implode(', ', $decl) . ")\n{\n$body}\n";
    $map[$name] = 'E2E\\Hook\\' . $name;
}
$out .= "}\n";
@mkdir(__DIR__ . '/gen');
file_put_contents(__DIR__ . '/gen/hooks.php', $out);
file_put_contents(__DIR__ . '/gen/map.php', "<?php\n// GENERATED by tests/e2e/gen-hooks.php\nreturn " . var_export(['functions' => $map, 'classes' => []], true) . ";\n");
fwrite(STDERR, count($map) . " hooks, " . count($skipped) . " skipped\nOptional parameters without a known default (named-argument skipping differs):\n  " . implode("\n  ", $noDefault) . "\n");
fwrite(STDERR, "Skipped (non str*/array_*): " . implode(' ', array_filter($skipped, fn ($s) => !str_starts_with($s, 'str') && !str_starts_with($s, 'array_') || str_starts_with($s, 'stream_'))) . "\n");
